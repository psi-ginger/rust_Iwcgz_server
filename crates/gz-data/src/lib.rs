/// Whether `item_unique` may be stacked, i.e. the legacy `cltItem::CanPile`.
///
/// A unique that is not in the table is not pileable: the legacy returns false
/// when `FindItemRefFromUnique` finds no type (type 0).
#[must_use]
pub fn is_pileable(item_unique: u16) -> bool {
    PILEABLE.binary_search(&item_unique).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_for_the_binary_search() {
        assert!(PILEABLE.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn consumables_materials_and_boxes_stack_but_equipment_does_not() {
        // The first item of every pileable category is in the table.
        let pileable = [
            1701,  // composition material
            2000,  // heal
            3543,  // food
            4000,  // book
            5000,  // mineral
            5600,  // animal
            6050,  // tree
            7000,  // cloth
            8315,  // premium
            7800,  // etc
            8800,  // scroll
            12000, // doll
            13000, // eventitem
            13002, // box
            16000, // seafood
            24000, // ticket
            24100, // quest
        ];
        for unique in pileable {
            assert!(is_pileable(unique), "expected {unique} to be pileable");
        }
        // Weapons, armour and accessories do not stack.
        assert!(!is_pileable(1)); // first sword
        assert!(!is_pileable(600)); // first armour
        assert!(!is_pileable(7500)); // first ring
        // Unknown uniques are not pileable, like the legacy's type-0 result.
        assert!(!is_pileable(0));
        assert!(!is_pileable(u16::MAX));
    }
}
