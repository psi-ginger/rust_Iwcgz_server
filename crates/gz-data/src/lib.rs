//! Server-side master data the runtime needs but the client data does not
//! provide as-is.
//!
//! Six things live here: [`npc`] (static town-NPC placements, generated from
//! `NPCGroup\*.txt` + `KindInfo_Unique.txt`), [`kindinfo`] (the monster
//! kind-data files and the runtime base-stat math), [`drops`] (the capture and
//! monster-drop table and its drop-string grammar), [`spawn`] (safe spawn-point
//! filtering and the roam leash for monster groups, over [`map`]'s collision
//! grid), [`levelup`] (`LevelUpExp.dat`, the cumulative exp per level), and the
//! pileability table below.
//!
//! [`npcgroup`] is the runtime half of the same `NPCGroup\*.txt` files the
//! `npc` table is generated from: the *field* groups (radius > 1, several per
//! kind) the generator refuses, parsed so a live server can spawn them.
//!
//! The monster tables [`kindinfo`] and [`drops`] parse have a committed runtime
//! master under `data/` — the Korean-baseline merge generated by
//! `scripts/generate-kr-canonical-tables.ps1`
//! (`docs/DESIGN_MONSTER_KR_BASELINE_STRATEGY.md`).
//!
//! # Pileability
//!
//! The legacy merges two slots that hold the same item only when the item is
//! *pileable*: `cltItem::CanPile` (`ItemUnit.cpp:1458`) returns true only when
//! the item's type does **not** carry `ITEMATB_OBJECT`, and it returns **false**
//! for an item whose type is unknown (type 0). Every weapon, armour piece,
//! accessory and avatar piece carries `ITEMATB_OBJECT`, as do the crafting
//! objects PAPER, IRON, DISH and FISHINGROD.
//!
//! An item's type comes from the data file it is loaded from
//! (`cltItemManagerCommon::SetItemData`, `cltItem-SetItemData.Cpp`), and the
//! per-type `ITEMATB_OBJECT` flag is the hard-coded table in
//! `cltItemManagerCommon::SetItemType` in the same file. [`is_pileable`] is the
//! resulting per-unique answer for the English data set, shipped as a sorted
//! table so the server reads no data files at runtime.
//!
//! The table is the union, deduplicated and sorted, of the first column of the
//! English `Item/Data/ItemType*E.txt` files whose type lacks `ITEMATB_OBJECT`:
//! HEAL, FOOD, BOOK, MINERAL, ANIMAL, TREE, CLOTH, SEAFOOD, ETC, SCROLL, DOLL,
//! TICKET, EVENTITEM, QUEST, BOX, PREMIUM and COMPOSITIONMATERIAL. Regenerate it
//! with `scripts/generate-pileable-table.ps1` whenever the GameServer item data
//! changes (`-Check` verifies the committed table); a unique that is not listed
//! is not pileable, matching the legacy's type-0 result.
//!
//! Two edge cases are baked into the table:
//! - CRYSTAL stays non-pileable: its type carries `ITEMATB_OBJECT` when
//!   `Switch_Artifact` is off (the default `else` branch of `SetItemType`).
//! - English `SetItemData` does not load every file on disk (e.g. `ItemBoxE`,
//!   `SoulGuardE`), so those uniques have no type and are non-pileable too.

