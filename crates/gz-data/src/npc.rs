//! Static town-NPC placements — the avatars a joining client is told about in a
//! `GAMEMSG_RESPONSE_LOGINMANY` (6) body (T-019 slice 2).
//!
//! # What is in here, and what is not
//!
//! Only the *placement* is data: which kind stands on which tile of which map.
//! The kind's id comes from the client's own `Data\KindInfo_Unique.txt` (the same
//! file the client resolves the sprite and display name from), and the rectangle
//! comes from `NPCGroup\*.txt`, which is the file the legacy server loads
//! (`common\NPCManager\NPC.cpp`, groups into `cltNPCGroup`).
//!
//! The table is **generated, never typed**:
//! `scripts\generate-npc-placements.ps1` applies the recipe above, refuses a kind
//! with no id, a group on another map, a `Radius` other than 1, a `MinNum` other
//! than 1 and two NPCs on one tile, and its `-Check` mode fails when the committed
//! table drifts from the data. It currently covers map 158 (Hanyang) — the only
//! map this port serves — from 37 group files, of which three
//! (`npcquest1/2/3.txt`, kinds `KIND_QUESTNPC1`, `KIND_QUESTETC1`,
//! `KIND_QUESTNPC2`) name kinds that exist in no shipped kind table and are
//! skipped as unrenderable rather than guessed.
//!
//! # The NPC's id on the wire
//!
//! A static NPC needs a `uiMakeCharUnique` that the client treats as an NPC:
//! `IsNPC(x)` is `x >= MAX_PERSON_NUMBER + MAX_INSTANCE_NPC_NUMBER` (3000 + 5500)
//! and `< MAX_CHAR_NUMBER` (`CommonHeader.h:639`), so ids start at
//! [`NPC_CHAR_UNIQUE_BASE`] and are assigned by table position — the same tile is
//! the same id on every restart, which the client's `CharUniqueInfo` cache
//! depends on.

/// One static NPC: a kind standing on a tile.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct NpcPlacement {
    /// `uiMakeCharKind` — a `KindInfo_Unique.txt` id. This is what the client
    /// draws and names the avatar from; the record carries no name.
    pub kind: u16,
    /// The server-side map id (`Data\mapinfoE.txt`), not the client's index. The
    /// encoder converts with `gz_proto::game::client_map_index`.
    pub map_id: i32,
    /// Tile x, the group rectangle's centre (all shipped town groups have
    /// `Radius` 1, so the centre is inside the 3x3).
    pub x: u16,
    /// Tile y.
    pub y: u16,
    /// The group's `Level` column — 1 for every town NPC.
    pub level: u8,
}

