/// The first `uiMakeCharUnique` a static NPC may use: `MAX_PERSON_NUMBER` (3000)
/// plus `MAX_INSTANCE_NPC_NUMBER` (5500), the lower bound of `IsNPC`
/// (`CommonHeader.h:559-565`, `:639`).
pub const NPC_CHAR_UNIQUE_BASE: u16 = 8500;

/// Every placement on `map_id`, in table order.
pub fn placements_on(map_id: i32) -> impl Iterator<Item = &'static NpcPlacement> {
    NPC_PLACEMENTS.iter().filter(move |p| p.map_id == map_id)
}

/// The char-unique a placement is announced with: the table position offset by
/// [`NPC_CHAR_UNIQUE_BASE`], so it is stable across restarts.
///
/// Returns `None` if the id would not fit [`u16`] or the placement is not in
/// [`NPC_PLACEMENTS`] (a caller-invented placement has no agreed id).
#[must_use]
pub fn char_unique_for(placement: &NpcPlacement) -> Option<u16> {
    let index = NPC_PLACEMENTS.iter().position(|p| p == placement)?;
    NPC_CHAR_UNIQUE_BASE.checked_add(u16::try_from(index).ok()?)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_hanyang_and_sarah_stands_where_the_group_file_says() {
        assert!(!NPC_PLACEMENTS.is_empty());
        assert!(
            NPC_PLACEMENTS.iter().all(|p| p.map_id == 158),
            "the shipped table is map 158 only"
        );
        // `NPCGroup\npcpalace04.txt`: KIND_WAITINGMAN at 158 (16,82); its kind id
        // is 40 in `Data\KindInfo_Unique.txt`.
        let sarah = NPC_PLACEMENTS
            .iter()
            .find(|p| p.kind == 40)
            .expect("KIND_WAITINGMAN is placed");
        assert_eq!((sarah.x, sarah.y), (16, 82));
        assert_eq!(sarah.level, 1);
    }

    #[test]
    fn placements_on_filters_by_map() {
        assert_eq!(placements_on(158).count(), NPC_PLACEMENTS.len());
        assert_eq!(placements_on(1).count(), 0);
    }

    #[test]
    fn every_npc_id_is_inside_the_clients_npc_range_and_unique() {
        let mut ids = Vec::new();
        for placement in NPC_PLACEMENTS {
            let id = char_unique_for(placement).expect("a table placement has an id");
            assert!(
                (NPC_CHAR_UNIQUE_BASE..19999).contains(&id),
                "NPC {id} must satisfy IsNPC"
            );
            ids.push(id);
        }
        let mut sorted = ids.clone();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(sorted.len(), ids.len(), "two NPCs share a char-unique");

        // A placement that is not in the table has no agreed id.
        assert!(
            char_unique_for(&NpcPlacement {
                kind: 1,
                map_id: 158,
                x: 0,
                y: 0,
                level: 1
            })
            .is_none()
        );
    }

    #[test]
    fn no_two_table_rows_share_a_tile_and_kind() {
        let mut seen = std::collections::HashSet::new();
        for p in NPC_PLACEMENTS {
            assert!(
                seen.insert((p.kind, p.x, p.y)),
                "duplicate placement {p:?} — the generator refuses these"
            );
        }
    }
}
