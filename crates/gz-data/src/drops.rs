//! The capture-and-drop table — the KR baseline's `CharInfo\CharItemInfo.txt` in
//! the English six-column schema — and the drop-string grammar the legacy parses
//! a monster kind's `ItemInfo` cell with.
//!
//! # The file
//!
//! `cltKindInfoSet::SetCharItemInfo`
//! (`common\Char\KindInfo\kindinfo-Manager.cpp:1239`) loads
//! `CharInfo\CharItemInfoK|E|…txt` per service area (`:362`, `:376`), column table
//! at `:1267-1276`: `Char Name CaptureLevel CaptPbt AdvPbt ItemInfo`. The row joins
//! on the kind code (`FindKindFromCode`, `:1287`); `CaptureLevel / CaptPbt /
//! AdvPbt` land on the kind's capture fields (`kindinfo.h:433-435`) and `ItemInfo`
//! goes through `cltKindInfo::AnalyzeItemInfo` (`kindinfo.cpp:249-416`).
//!
//! The committed runtime master is `data/CharItemInfoCanonical.txt` — the KR
//! baseline merge generated by `scripts/generate-kr-canonical-tables.ps1` (see
//! `docs/DESIGN_MONSTER_KR_BASELINE_STRATEGY.md`). The shipped EN file has the same
//! schema, so one parser reads both.
//!
//! # The drop grammar ([`parse_drop_list`])
//!
//! Entries are `+`-separated, and a cell of `NULL(0)` means "drops nothing"
//! (`:328-331`). Inside an entry the legacy state machine (`:277-411`) collects the
//! digits before `(` as the item unique, then the first number inside the parens as
//! the **probability**, the number after `-` as the minimum count and the number
//! after `:` as the maximum — so the shipped `2002(2500-1:3)` is 1-in-10000
//! probability 2500, minimum 1, maximum 3, **not** `min-max:probability`. Omitted
//! fields default: `5000(1000)` is a probability with one item (`:361-365`), and
//! `-min` without `:max` leaves the max buffer empty, which `_tstoi`s to 0 and is
//! raised to 1 (`:351`).
//!
//! Normalisation on the way in (`:344-359`): either count ≤ 0 becomes 1, both clamp
//! to `MAX_MONSTERDROPITEM_NUM` (20, `CommonLogic.h`), and a minimum above the
//! maximum collapses back to 1. Probability is a 1-in-10000 chance
//! (`kindinfo.h:115`) and a kind stores at most `MAX_ITEM_PROBABILITY_PER_KIND`
//! (5, `kindinfo.h:128`) entries — the KR starter rows sit exactly at that cap. An
//! entry whose unique is not a positive number contributes nothing (`_tstoi` gives
//! 0, `FindItemRefFromUnique` fails, `:334-337`); the legacy's second gate — the
//! unique must exist in the item table — is a runtime check this parse cannot make.
//! The legacy's 100-character buffer guards (`:383`, `:392`, `:402`) abort the whole
//! parse; the data here is trusted and committed, so this port collects without the
//! guards.

use crate::kindinfo::{KindDataError, data_rows, decode_utf16le, field, wtoi};

/// `MAX_MONSTERDROPITEM_NUM` (`common\CommonLogic\CommonLogic.h`) — the per-entry
/// minimum/maximum drop-count clamp.
pub const MAX_MONSTERDROP_ITEM_NUM: i32 = 20;

/// `MAX_ITEM_PROBABILITY_PER_KIND` (`kindinfo.h:128`) — how many drop entries a
/// kind can hold; the legacy `Add` stops silently at the array bound.
pub const MAX_ITEM_PROBABILITY_PER_KIND: usize = 5;

/// One `+`-separated drop entry of a kind's `ItemInfo` cell, normalised the way
/// `AnalyzeItemInfo` stores it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DropEntry {
    /// The item unique the drop rolls for.
    pub item_unique: i32,
    /// 1-in-10000 chance to drop (`kindinfo.h:115`).
    pub probability: i32,
    /// Maximum stack dropped (`siItemNum`, `kindinfo.h:116`).
    pub max_num: i32,
    /// Minimum stack dropped (`siItemMinNum`, `kindinfo.h:117`).
    pub min_num: i32,
}

/// One `CharItemInfo` row in the English six-column schema.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct CharDropRow {
    /// Column 0 (`Char`) — the kind code, the join key with the attack table.
    pub code: String,
    /// Column 1 (`Name`) — the display name (English in the canonical table).
    pub name: String,
    /// Column 2 — the capture skill level needed (`kindinfo.h:433`).
    pub capture_level: i32,
    /// Column 3 (`CaptPbt`) — the basic capture chance (`kindinfo.h:434`).
    pub capture_pbt: i32,
    /// Column 4 (`AdvPbt`) — the extra capture chance per capture-skill level
    /// (`kindinfo.h:435`).
    pub adv_pbt: i32,
    /// Column 5 (`ItemInfo`) — the parsed drop list, in cell order.
    pub drops: Vec<DropEntry>,
}

/// Which buffer the legacy's state machine is filling — its
/// `itemnameswith / itemminnumswitch / itemnumswitch` flags folded into one state
/// (`kindinfo.cpp:277-411`).
#[derive(Clone, Copy, PartialEq, Eq)]
enum Section {
    /// Before `(`: the item unique.
    Unique,
    /// After `(`: the probability (the first number inside the parens).
    Probability,
    /// After `-`: the minimum count.
    Min,
    /// After `:`: the maximum count.
    Max,
}

/// Parse one `ItemInfo` cell (`cltKindInfo::AnalyzeItemInfo`,
/// `kindinfo.cpp:249-416`). Uniques that are not positive numbers and entries
/// without their closing `)` are dropped, exactly as the legacy leaves them out.
#[must_use]
pub fn parse_drop_list(text: &str) -> Vec<DropEntry> {
    let mut out = Vec::new();
    let mut unique = String::new();
    let mut probability = String::new();
    let mut min = String::new();
    let mut max = String::new();
    let mut section = Section::Unique;
    let mut have_max = false;
    for c in text.chars() {
        match c {
            // Spaces are ignored everywhere (`:285`).
            ' ' => {}
            '+' => {
                unique.clear();
                probability.clear();
                min.clear();
                max.clear();
                section = Section::Unique;
                have_max = false;
            }
            '(' => {
                section = Section::Probability;
                have_max = false;
            }
            // `-` and `:` only switch sections once the parens are open; before
            // that the legacy's name-first branch collects them into the unique
            // (`:379-384`).
            '-' if section != Section::Unique => section = Section::Min,
            ':' if section != Section::Unique => {
                section = Section::Max;
                have_max = true;
            }
            ')' => {
                // `NULL` aborts the rest of the cell, keeping the entries already
                // added (`:328-331`).
                if unique.trim() == "NULL" {
                    break;
                }
                let item_unique = wtoi(&unique);
                if item_unique > 0 {
                    let (mut max_num, mut min_num) = if have_max {
                        let mut max_num = wtoi(&max);
                        if max_num <= 0 {
                            max_num = 1;
                        }
                        let mut min_num = wtoi(&min);
                        if min_num <= 0 {
                            min_num = 1;
                        }
                        (max_num, min_num)
                    } else {
                        // No `:` seen: a probability with one item, the legacy's
                        // `else` branch (`:361-365`).
                        (1, 1)
                    };
                    max_num = max_num.min(MAX_MONSTERDROP_ITEM_NUM);
                    min_num = min_num.min(MAX_MONSTERDROP_ITEM_NUM);
                    // A minimum above the maximum collapses to the minimum
                    // (`:358-359`).
                    if min_num > max_num {
                        min_num = 1;
                    }
                    out.push(DropEntry {
                        item_unique,
                        probability: wtoi(&probability),
                        max_num,
                        min_num,
                    });
                }
                unique.clear();
                probability.clear();
                min.clear();
                max.clear();
                section = Section::Unique;
                have_max = false;
            }
            _ => match section {
                Section::Unique => unique.push(c),
                Section::Probability => probability.push(c),
                // The legacy skips the section characters themselves (`:388`,
                // `:398`); the match arms above already consumed them.
                Section::Min => min.push(c),
                Section::Max => max.push(c),
            },
        }
    }
    out
}

/// Parse a whole `CharItemInfo` file (UTF-16LE bytes as shipped).
pub fn parse_char_drops(bytes: &[u8]) -> Result<Vec<CharDropRow>, KindDataError> {
    let text = decode_utf16le(bytes);
    let mut out = Vec::new();
    for row in data_rows(&text)? {
        // `if (szcode[0] != NULL)` (`kindinfo-Manager.cpp:1284`).
        let code = field(row, 0);
        if code.is_empty() {
            continue;
        }
        out.push(CharDropRow {
            code: code.to_owned(),
            name: field(row, 1).to_owned(),
            capture_level: wtoi(field(row, 2)),
            capture_pbt: wtoi(field(row, 3)),
            adv_pbt: wtoi(field(row, 4)),
            drops: parse_drop_list(field(row, 5)),
        });
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A tiny UTF-16LE `NDataLoader` item file, same shape as the shipped ones.
    fn file(rows: &[&str]) -> Vec<u8> {
        let mut text = String::from(
            "Preamble\tjunk\r\n<Data>\r\nChar\tName\tCaptureLevel\tCaptPbt\tAdvPbt\tItemInfo\r\n",
        );
        for row in rows {
            text.push_str(row);
            text.push_str("\r\n");
        }
        text.push_str("<End>\t\t\r\n");
        text.encode_utf16().flat_map(|u| u.to_le_bytes()).collect()
    }

    fn entry(item_unique: i32, probability: i32, max_num: i32, min_num: i32) -> DropEntry {
        DropEntry {
            item_unique,
            probability,
            max_num,
            min_num,
        }
    }

    #[test]
    fn the_paren_fields_are_probability_min_and_max_in_that_order() {
        // `2002(2500-1:3)` — probability 2500, minimum 1, maximum 3.
        assert_eq!(
            parse_drop_list("2002(2500-1:3)"),
            vec![entry(2002, 2500, 3, 1)]
        );
    }

    #[test]
    fn omitted_fields_and_out_of_order_counts_follow_the_legacy_defaults() {
        // Probability only: one item (`:361-365`).
        assert_eq!(parse_drop_list("5000(1000)"), vec![entry(5000, 1000, 1, 1)]);
        // `-min` without `:max`: the empty max buffer raises to 1 (`:351`).
        assert_eq!(
            parse_drop_list("24015(500-1)"),
            vec![entry(24015, 500, 1, 1)]
        );
        // Minimum above maximum collapses to 1 (`:358-359`).
        assert_eq!(
            parse_drop_list("1234(30-99:2)"),
            vec![entry(1234, 30, 2, 1)]
        );
        // Both counts clamp to MAX_MONSTERDROPITEM_NUM.
        assert_eq!(
            parse_drop_list("1234(30-1:99)"),
            vec![entry(1234, 30, MAX_MONSTERDROP_ITEM_NUM, 1)]
        );
        // A zero count raises to 1 before the clamp (`:351`, `:355`).
        assert_eq!(parse_drop_list("1234(30-0:0)"), vec![entry(1234, 30, 1, 1)]);
    }

    #[test]
    fn null_drops_nothing_and_a_non_numeric_unique_contributes_nothing() {
        assert!(parse_drop_list("NULL(0)").is_empty());
        assert!(parse_drop_list("ABC(100)").is_empty());
        // `NULL` stops the cell; entries added before it stay (`:328-331`).
        assert_eq!(
            parse_drop_list("2002(100-1:1)+NULL(0)+3000(50)"),
            vec![entry(2002, 100, 1, 1)]
        );
    }

    #[test]
    fn entries_are_split_on_plus_and_spaces_are_ignored() {
        assert_eq!(
            parse_drop_list("2020(2000-1:4)+3060( 2000 - 1 : 3 )"),
            vec![entry(2020, 2000, 4, 1), entry(3060, 2000, 3, 1)]
        );
    }

    #[test]
    fn an_unterminated_trailing_entry_is_dropped() {
        assert_eq!(
            parse_drop_list("2002(2500-1:3)+3070(2500-1:3"),
            vec![entry(2002, 2500, 3, 1)]
        );
    }

    #[test]
    fn the_row_parser_reads_capture_columns_and_the_drop_cell() {
        let rows = parse_char_drops(&file(&[
            "KIND_A\tA\t2\t300\t100\t2002(2500-1:3)",
            // Empty code: skipped (`kindinfo-Manager.cpp:1284`).
            "\tB\t1\t1\t1\tNULL(0)",
        ]))
        .expect("parses");
        assert_eq!(rows.len(), 1);
        assert_eq!(rows[0].code, "KIND_A");
        assert_eq!(rows[0].name, "A");
        assert_eq!(
            (rows[0].capture_level, rows[0].capture_pbt, rows[0].adv_pbt),
            (2, 300, 100)
        );
        assert_eq!(rows[0].drops, vec![entry(2002, 2500, 3, 1)]);
    }

    /// The committed KR-baseline merge, parsed end to end. The file is in the
    /// repository, so this test always runs.
    #[test]
    fn the_canonical_table_carries_the_korean_capture_and_drop_values() {
        let path = std::path::Path::new(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/data/CharItemInfoCanonical.txt"
        ));
        let bytes = std::fs::read(path).expect("the canonical table is committed");
        let rows = parse_char_drops(&bytes).expect("parses");
        assert_eq!(rows.len(), 334, "the EN row set, in EN order");

        // KIND_RACCOON (map 108 starter): the KR capture numbers and the KR drop
        // string, with the English display name layered on top.
        let raccoon = rows
            .iter()
            .find(|r| r.code == "KIND_RACCOON")
            .expect("RACCOON row");
        assert_eq!(raccoon.name, "Evil Raccoon");
        assert_eq!(
            (raccoon.capture_level, raccoon.capture_pbt, raccoon.adv_pbt),
            (1, 300, 100)
        );
        assert_eq!(
            raccoon.drops,
            vec![
                entry(2002, 2500, 3, 1),
                entry(3070, 2500, 3, 1),
                entry(2020, 1000, 2, 1),
                entry(6010, 700, 2, 1),
                entry(5000, 700, 2, 1),
            ]
        );
        // The KR starter rows sit exactly at the legacy per-kind cap.
        assert_eq!(raccoon.drops.len(), MAX_ITEM_PROBABILITY_PER_KIND);

        // The other three map-108 starters are KR-upgraded too.
        for (code, first) in [
            ("KIND_FLOWERPIG", entry(2020, 2000, 4, 1)),
            ("KIND_RABBIT", entry(3090, 2000, 3, 1)),
            ("KIND_MUSHROOM", entry(3030, 2500, 2, 1)),
        ] {
            let row = rows.iter().find(|r| r.code == code).expect("starter row");
            assert_eq!(row.capture_pbt, 300, "{code}");
            assert_eq!(row.drops.first(), Some(&first), "{code}");
        }

        // An EN-only kind is provisional: its row is still the EN one.
        let berserker = rows
            .iter()
            .find(|r| r.code == "KIND_BERSERKER")
            .expect("BERSERKER row");
        assert_eq!(berserker.capture_pbt, 0);
        assert_eq!(berserker.drops.first().map(|d| d.item_unique), Some(2715));
    }
}
