//! Emits the Rust opcode module for a parsed legacy enum.

use std::collections::HashSet;
use std::fmt::Write as _;

use crate::parse::EnumDef;

/// Configuration for one generated module.
pub struct EmitSpec<'a> {
    /// Source path recorded in the generated header comment.
    pub source: &'a str,
    /// Legacy identifier prefix stripped from variant names (e.g. `GAMEMSG_`).
    pub prefix: &'a str,
    /// Rust type name (e.g. `GameMsg`).
    pub ty: &'a str,
    /// Rust function name for the wire-value-to-name lookup.
    pub name_fn: &'a str,
    /// Free function returning the number of entries in the enum.
    pub count_fn: &'a str,
    /// Documentation blurb placed above the enum.
    pub doc: &'a str,
}

/// A legacy enumerator paired with the Rust variant name it maps to.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Variant<'a> {
    pub legacy: &'a str,
    pub value: u16,
    pub variant: String,
}

/// Derives the Rust variant name for every enumerator, rejecting any that would
/// not compile.
///
/// `GAMEMSG_REQUEST_CHAT` with prefix `GAMEMSG_` becomes `RequestChat`. Two
/// distinct legacy names can normalise to the same Rust identifier (`GAMEMSG_A_B`
/// and `GAMEMSG_A__B` both become `AB`), which is a hard error rather than a
/// silently duplicated variant. A C *alias* — two enumerators sharing a value —
/// is rejected for the same reason: neither the enum nor the lookup tables can
/// express it.
pub fn build_variants<'a>(
    def: &'a EnumDef,
    spec: &EmitSpec<'_>,
) -> Result<Vec<Variant<'a>>, String> {
    let mut seen: HashSet<&str> = HashSet::with_capacity(def.members.len());
    let mut out: Vec<Variant<'a>> = Vec::with_capacity(def.members.len());

    for member in &def.members {
        let variant = variant_name(&member.name, spec.prefix);
        if variant.is_empty() {
            return Err(format!(
                "line {}: `{}` reduces to an empty Rust identifier",
                member.line, member.name
            ));
        }
        if !is_plain_ident(&variant) {
            return Err(format!(
                "line {}: `{}` reduces to `{variant}`, which is not a usable Rust identifier",
                member.line, member.name
            ));
        }
        if variant == "Self" {
            return Err(format!(
                "line {}: `{}` reduces to `Self`, which cannot be a variant name",
                member.line, member.name
            ));
        }
        if !seen.insert(member.name.as_str()) {
            return Err(format!(
                "line {}: duplicate enumerator `{}`",
                member.line, member.name
            ));
        }
        // A C alias (two enumerators sharing a value) is legal C, but it is not
        // expressible here: `#[repr(u16)]` would give the enum two identical
        // discriminants and both lookup tables would get duplicate `match` arms,
        // so the generated file would not compile. Caught here so the failure is
        // one sentence pointing at the header line.
        if let Some(clash) = out.iter().find(|v| v.value == member.value) {
            return Err(format!(
                "line {}: `{}` and `{}` both have value {}; C aliases cannot be \
                 represented as an enum discriminant",
                member.line, member.name, clash.legacy, member.value
            ));
        }
        if let Some(clash) = out.iter().find(|v| v.variant == variant) {
            return Err(format!(
                "line {}: `{}` and `{}` both normalise to the Rust variant `{variant}`",
                member.line, member.name, clash.legacy
            ));
        }
        out.push(Variant {
            legacy: &member.name,
            value: member.value,
            variant,
        });
    }

    Ok(out)
}

/// Renders the complete Rust module.
pub fn emit(def: &EnumDef, spec: &EmitSpec<'_>) -> Result<String, String> {
    let variants = build_variants(def, spec)?;
    let mut out = String::with_capacity(def.members.len() * 96);

    out.push_str("//! Generated by `tools/codegen` -- DO NOT EDIT.\n");
    out.push_str("//!\n");
    let _ = writeln!(
        out,
        "//! Source: `{}` ({} lines {}-{})",
        spec.source,
        def.describe(),
        def.start_line,
        def.end_line
    );
    out.push_str("//!\n");
    out.push_str("//! Regenerate with `cargo run -p codegen -- all`. The discriminants are\n");
    out.push_str(
        "//! the exact legacy numbers: wire compatibility with the shipped client depends\n\
         //! on them. Every entry keeps its legacy line number for traceability to the\n\
         //! header.\n\n",
    );

    let _ = writeln!(out, "/// {}", spec.doc);
    out.push_str("#[repr(u16)]\n");
    out.push_str("#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]\n");
    let _ = writeln!(out, "pub enum {} {{", spec.ty);
    for v in &variants {
        let _ = writeln!(out, "    /// Legacy `{}` = {}", v.legacy, v.value);
        let _ = writeln!(out, "    {} = {},", v.variant, v.value);
    }
    out.push_str("}\n\n");

    let _ = writeln!(out, "impl {} {{", spec.ty);
    out.push_str("    /// The numeric opcode as it appears on the wire.\n");
    out.push_str("    #[must_use]\n");
    out.push_str("    pub const fn id(self) -> u16 {\n        self as u16\n    }\n\n");
    out.push_str("    /// The legacy C enumerator name (e.g. `GAMEMSG_REQUEST_CHAT`).\n");
    out.push_str("    #[must_use]\n");
    let _ = writeln!(
        out,
        "    pub const fn legacy_name(self) -> &'static str {{\n        {}(self as u16)\n    }}",
        spec.name_fn
    );
    out.push_str("}\n\n");

    let _ = writeln!(
        out,
        "/// Number of entries in the legacy enum, including any terminator.\n\
         ///\n\
         /// Generated from `{}`.",
        spec.source
    );
    out.push_str("#[must_use]\n");
    let _ = writeln!(
        out,
        "pub const fn {}() -> usize {{\n    {}\n}}\n",
        spec.count_fn,
        variants.len()
    );

    out.push_str("/// Maps a wire opcode to its legacy C enumerator name.\n");
    out.push_str("///\n");
    out.push_str("/// The legacy numbering is sparse, so unused numbers return `\"<unknown>\"`.\n");
    out.push_str("#[must_use]\n");
    let _ = writeln!(
        out,
        "pub const fn {}(value: u16) -> &'static str {{",
        spec.name_fn
    );
    out.push_str("    match value {\n");
    for v in &variants {
        let _ = writeln!(out, "        {} => \"{}\",", v.value, v.legacy);
    }
    out.push_str("        _ => \"<unknown>\",\n    }\n}\n\n");

    out.push_str("/// Maps a wire opcode to its enum variant, or `None` for unused numbers.\n");
    out.push_str("#[must_use]\n");
    let _ = writeln!(
        out,
        "pub const fn from_id(value: u16) -> Option<{}> {{",
        spec.ty
    );
    out.push_str("    match value {\n");
    for v in &variants {
        let _ = writeln!(
            out,
            "        {} => Some({}::{}),",
            v.value, spec.ty, v.variant
        );
    }
    out.push_str("        _ => None,\n    }\n}\n");

    Ok(out)
}

/// `GAMEMSG_REQUEST_CHAT` minus prefix `GAMEMSG_` -> `RequestChat`.
fn variant_name(legacy: &str, prefix: &str) -> String {
    let body = legacy.strip_prefix(prefix).unwrap_or(legacy);
    let mut out = String::with_capacity(body.len());
    for token in body.split('_').filter(|t| !t.is_empty()) {
        let mut chars = token.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.extend(chars.as_str().chars().flat_map(char::to_lowercase));
        }
    }
    out
}

fn is_plain_ident(s: &str) -> bool {
    let mut chars = s.chars();
    chars.next().is_some_and(|c| c.is_ascii_alphabetic())
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse::{EnumDef, EnumSelector, Enumerator, parse_enum, parse_selected};

    fn spec<'a>() -> EmitSpec<'a> {
        EmitSpec {
            source: "MsgType.h",
            prefix: "GAMEMSG_",
            ty: "GameMsg",
            name_fn: "name",
            count_fn: "count",
            doc: "test enum",
        }
    }

    #[test]
    fn variant_names_are_pascal_case() {
        assert_eq!(
            variant_name("GAMEMSG_REQUEST_CHAT", "GAMEMSG_"),
            "RequestChat"
        );
        assert_eq!(
            variant_name("GAMEMSG_REQUEST_BBB_CHECK_PlAY_CONDITION", "GAMEMSG_"),
            "RequestBbbCheckPlayCondition"
        );
        assert_eq!(variant_name("GAMEMSG_END", "GAMEMSG_"), "End");
    }

    #[test]
    fn normalising_collision_is_rejected() {
        let src = b"enum e{\n\tGAMEMSG_A_B = 1,\n\tGAMEMSG_A__B,\n};\n";
        let def = parse_enum(src, "e").unwrap();
        let err = build_variants(&def, &spec()).unwrap_err();
        assert!(err.contains("normalise"), "{err}");
    }

    #[test]
    fn reserved_variant_name_is_rejected() {
        let src = b"enum e{\n\tGAMEMSG_SELF = 1,\n};\n";
        let def = parse_enum(src, "e").unwrap();
        assert!(build_variants(&def, &spec()).is_err());
    }

    #[test]
    fn alias_value_is_rejected() {
        // Legal C, but it cannot be an enum discriminant nor a `match` arm.
        let src = b"enum e{\n\tGAMEMSG_A = 1,\n\tGAMEMSG_B = 1,\n};\n";
        let def = parse_enum(src, "e").unwrap();
        let err = build_variants(&def, &spec()).unwrap_err();
        assert!(err.contains("both have value 1"), "{err}");
    }

    #[test]
    fn empty_variant_name_is_rejected() {
        let src = b"enum e{\n\tGAMEMSG_ = 1,\n};\n";
        let def = parse_enum(src, "e").unwrap();
        assert!(build_variants(&def, &spec()).is_err());
    }

    #[test]
    fn emits_expected_shape() {
        let def = EnumDef {
            tag: "eGameNetworkMsg".into(),
            start_line: 17,
            end_line: 21,
            members: vec![
                Enumerator {
                    name: "GAMEMSG_REQUEST_CHAT".into(),
                    value: 117,
                    line: 18,
                },
                Enumerator {
                    name: "GAMEMSG_END".into(),
                    value: 118,
                    line: 21,
                },
            ],
        };
        let out = emit(&def, &spec()).unwrap();
        assert!(out.contains("pub enum GameMsg {"), "{out}");
        assert!(out.contains("RequestChat = 117,"), "{out}");
        assert!(out.contains("End = 118,"), "{out}");
        assert!(
            out.contains("pub const fn count() -> usize {\n    2\n}"),
            "{out}"
        );
        assert!(out.contains("117 => \"GAMEMSG_REQUEST_CHAT\","), "{out}");
        assert!(out.contains("Some(GameMsg::RequestChat)"), "{out}");
        assert!(out.contains("_ => \"<unknown>\","), "{out}");
        assert!(out.contains("pub const fn name(value: u16)"), "{out}");
    }

    #[test]
    fn output_is_deterministic() {
        let def = parse_enum(b"enum e{\n\tGAMEMSG_A = 1,\n};\n", "e").unwrap();
        assert_eq!(emit(&def, &spec()).unwrap(), emit(&def, &spec()).unwrap());
    }

    #[test]
    fn anonymous_enum_is_parsed_and_labelled() {
        // Mirrors FrontMsg.h / AuthMsg.h, which use a bare `enum { ... }`.
        let src = b"enum {\n\tFRONTMSG_REQUEST_LOGIN = 1,\n\tFRONTMSG_RESPONSE_LOGIN = 1000,\n};\n";
        let def = parse_selected(
            src,
            EnumSelector::Anonymous {
                prefix: "FRONTMSG_",
            },
        )
        .unwrap();
        assert_eq!(def.tag, "");
        assert_eq!(def.describe(), "anonymous `enum`");
        assert_eq!(def.members.len(), 2);
        assert_eq!(def.members[1].value, 1000);
    }

    #[test]
    fn header_comment_distinguishes_tagged_from_anonymous() {
        let tagged = parse_enum(b"enum e{\n\tGAMEMSG_A = 1,\n};\n", "e").unwrap();
        assert!(
            emit(&tagged, &spec())
                .unwrap()
                .contains("(enum `e` lines 1-3)"),
            "tagged"
        );
        let anon = parse_selected(
            b"enum {\n\tGAMEMSG_A = 1,\n};\n",
            EnumSelector::Anonymous { prefix: "GAMEMSG_" },
        )
        .unwrap();
        assert!(
            emit(&anon, &spec())
                .unwrap()
                .contains("(anonymous `enum` lines 1-3)"),
            "anonymous"
        );
    }

    #[test]
    fn ambiguous_anonymous_selector_is_rejected() {
        let src = b"enum {\n\tFRONTMSG_A = 1,\n};\nenum {\n\tFRONTMSG_B = 1,\n};\n";
        let err = parse_selected(
            src,
            EnumSelector::Anonymous {
                prefix: "FRONTMSG_",
            },
        )
        .unwrap_err();
        assert!(err.message.contains("ambiguous"), "{err}");
    }

    #[test]
    fn anonymous_selector_with_no_match_is_rejected() {
        let err = parse_selected(
            b"enum {\n\tOTHER_A = 1,\n};\n",
            EnumSelector::Anonymous { prefix: "X_" },
        )
        .unwrap_err();
        assert!(err.message.contains("no anonymous enum block"), "{err}");
    }

    #[test]
    fn tag_selector_ignores_anonymous_blocks() {
        let src = b"enum {\n\tFRONTMSG_A = 1,\n};\nenum eTag{\n\tGAMEMSG_B = 5,\n};\n";
        let def = parse_enum(src, "eTag").unwrap();
        assert_eq!(def.tag, "eTag");
        assert_eq!(def.members.len(), 1);
        assert_eq!(def.members[0].value, 5);
    }

    #[test]
    fn generated_module_is_self_consistent() {
        // Every variant name emitted must be referenced in both lookup tables.
        let src = b"enum e{\n\tGAMEMSG_A = 1,\n\tGAMEMSG_B = 77,\n\tGAMEMSG_END = 78,\n};\n";
        let def = parse_enum(src, "e").unwrap();
        let out = emit(&def, &spec()).unwrap();
        let variants = build_variants(&def, &spec()).unwrap();
        for v in &variants {
            assert!(
                out.contains(&format!("Some(GameMsg::{})", v.variant)),
                "{}",
                v.variant
            );
            assert!(out.contains(&format!("\"{}\"", v.legacy)), "{}", v.legacy);
        }
        assert_eq!(
            out.matches("pub const fn ").count(),
            5,
            "expected id/legacy_name/name/count/from_id to be generated"
        );
    }
}
